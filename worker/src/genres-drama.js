export const DRAMA_GENRES = { male: MALE_GENRES, female: FEMALE_GENRES };

export const FREQ_LABEL = { male: '男频', female: '女频' };

export function dramaGenreIds(freq) {
  return (DRAMA_GENRES[freq] || MALE_GENRES).map((g) => g.id);
}

/** 根据频率与子类型 ID 查找类型定义；找不到回落该频率第一类。 */
export function findDramaGenre(freq, id) {
  const list = DRAMA_GENRES[freq] || MALE_GENRES;
  return list.find((g) => g.id === id) || list[0];
}
