// 续写轮：给模型已写正文末尾的锚点，要求从锚点之后直接接续。
export function continueInstruction(anchor) {
  return `上一轮篇幅未尽。下面是本节**已写成的全文**，请从它之后直接续写，把本节补足：

- 不要输出标题、不要输出书名、不要另起新节；
- 不要复述、改写已写部分，从末尾自然接续，保持文风与口吻一致；
- 若上一轮是因字数不足而止，只作补足，勿换话题、勿把说过的意思再说一遍；
- 义理若已说尽，在末尾另起一行输出 [章成]。

已写全文末句供你接续：「${anchor}」`;
}

